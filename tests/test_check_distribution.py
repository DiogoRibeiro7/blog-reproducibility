def write_distributions(
    directory: Path, source_files: dict[str, bytes], wheel_files: dict[str, bytes]
) -> tuple[Path, Path]:
    """Build tiny real archives without installing a package or accessing the network."""
    wheel = directory / "example.whl"
    with ZipFile(wheel, "w") as wheel_archive:
        for name, content in wheel_files.items():
            wheel_archive.writestr(name, content)
        wheel_archive.writestr("example-0.1.0.dist-info/METADATA", "Name: example\n")
    source = directory / "example.tar.gz"
    with tarfile.open(source, "w:gz") as source_archive:
        for name, content in source_files.items():
            member = tarfile.TarInfo("example-0.1.0/" + name)
            member.size = len(content)
            source_archive.addfile(member, io.BytesIO(content))
        metadata = tarfile.TarInfo("example-0.1.0/PKG-INFO")
        source_archive.addfile(metadata, io.BytesIO())
    return wheel, source


@pytest.fixture
def wheel_files(source_files: dict[str, bytes]) -> dict[str, bytes]:
    return {
        name.removeprefix("src/"): content
        for name, content in source_files.items()
        if name.startswith("src/")
    }


def test_complete_distributions_match_checkout(
    tmp_path: Path, source_files: dict[str, bytes], wheel_files: dict[str, bytes]
) -> None:
    # Local bytecode is generated by validation, not a required source input.
    cache = tmp_path / "src/blog_reproducibility/__pycache__/__init__.cpython-313.pyc"
    cache.parent.mkdir()
    cache.write_bytes(b"cache")
    (tmp_path / "scripts/cached.pyo").write_bytes(b"cache")
    wheel, source = write_distributions(tmp_path, source_files, wheel_files)
    check_contents(wheel, source, root=tmp_path)


@pytest.mark.parametrize("change", ["missing", "changed"])
@pytest.mark.parametrize(
    "path",
    [
        "blog_reproducibility/physics/seasons.py",
        "blog_reproducibility/common/house.mplstyle",
        "blog_reproducibility/py.typed",
    ],
)
def test_wheel_must_preserve_modules_and_resources(
    tmp_path: Path,
    source_files: dict[str, bytes],
    wheel_files: dict[str, bytes],
    path: str,
    change: str,
) -> None:
    if change == "missing":
        del wheel_files[path]
    else:
        wheel_files[path] += b"altered"
    wheel, source = write_distributions(tmp_path, source_files, wheel_files)
    with pytest.raises(RuntimeError) as error:
        check_contents(wheel, source, root=tmp_path)
    assert "Wheel differs from the checkout" in str(error.value)
    assert f"{change}=['{path}']" in str(error.value)


