@pytest.mark.parametrize("artifact", ["wheel", "source"])
def test_command_rejects_incomplete_distributions_before_installing(
    tmp_path: Path,
    source_files: dict[str, bytes],
    wheel_files: dict[str, bytes],
    monkeypatch: pytest.MonkeyPatch,
    artifact: str,
) -> None:
    def unexpected_environment(*args: object, **kwargs: object) -> None:
        pytest.fail("Incomplete distributions must fail before creating an environment")

    monkeypatch.setattr(check_distribution, "ROOT", tmp_path)
    monkeypatch.setattr(venv, "EnvBuilder", unexpected_environment)
    if artifact == "wheel":
        del wheel_files["blog_reproducibility/physics/seasons.py"]
    else:
        del source_files["data/economics/vintages.csv"]
    destination = tmp_path / "dist"
    destination.mkdir()
    write_distributions(destination, source_files, wheel_files)
    with pytest.raises(RuntimeError, match="differs from the checkout"):
        check_distribution.main()
